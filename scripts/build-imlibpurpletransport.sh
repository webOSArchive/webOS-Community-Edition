#!/bin/bash
# Builds imlibpurpletransport (the Synergy IM transport) for webOS CE from codepoet80's fork of
# imlibpurpleservice at the commit pinned in packages/webos-chat/TRANSPORT_COMMIT.
#
#   scripts/build-imlibpurpletransport.sh   -> build/work/transport-build/out/imlibpurpletransport
#
# Herrie's own build (webos-synergy-revival messaging/imlibpurpleservice/build.sh) needs his
# machine's staging trees. This rebuilds the same inputs from pinned public sources instead, with
# the same compiler flags, sources and link line:
#   toolchain  crosstool-NG arm-cortex_a8-linux-gnueabi (gcc 12.3, glibc 2.23 = synergy-glibc), in
#              ~/x-tools (override TC=)
#   glib       2.70.5 headers + an ARM glibconfig.h generated by meson (CE's runtime glib is 2.70.x)
#   db8        openwebos/db8 @ 8a9a902 -- the stock libmojo* ABI, as Herrie's build requires
#   ls2, PmLog openwebos/luna-service2 @ 0f38429, openwebos/PmLogLib @ d53ab57 (headers)
#   libpurple  pidgin 2.14.13 headers
#   tidy, opus tidy-html5 5.8.0, opus 1.3.1, libogg 1.3.5 headers
#   libraries  linked against the device's own: libmojo*/liblunaservice from the stock 3.0.5 rootfs
#              (build/work/webos, extracted by build/harness.py), libpurple and the synergy runtime
#              from the full-ce overlay in this repo
# The result is checked for the interpreter, NEEDED list and symbol versions the device provides.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
W=${W:-$ROOT/build/work/transport-build}
TC=${TC:-$HOME/x-tools/arm-cortex_a8-linux-gnueabi/bin/arm-cortex_a8-linux-gnueabi-}
IMLIB_URL=${IMLIB_URL:-https://github.com/codepoet80/imlibpurpleservice.git}
IMLIB_COMMIT=$(cat "$ROOT/packages/webos-chat/TRANSPORT_COMMIT")
STOCK=$ROOT/build/work/webos/nova-cust-image-topaz.rootfs.tar.gz
O=$ROOT/build/overlays/full-ce/rootfs
RT=$O/usr/palm/ce-seed/cryptofs/synergy-runtime
GV=2.70.5; MV=1.2.3

[ -x "${TC}g++" ] || { echo "toolchain not found: ${TC}g++" >&2; exit 1; }
[ -f "$STOCK" ] || { echo "stock rootfs not found: $STOCK (run build/harness.py extract)" >&2; exit 1; }
mkdir -p "$W/src" "$W/out"
cd "$W/src"

fetch() { [ -e "$2" ] || { curl -sSfL -o "$2.part" "$1" && mv "$2.part" "$2"; }; }
untar() { [ -d "$2" ] || tar -xf "$1"; }
gitat() { [ -d "$2" ] || { git clone -q "$1" "$2" && git -C "$2" checkout -q "$3"; }; }

# ---- sources ---------------------------------------------------------------------------------
fetch https://download.gnome.org/sources/glib/2.70/glib-$GV.tar.xz glib-$GV.tar.xz
fetch https://github.com/mesonbuild/meson/releases/download/$MV/meson-$MV.tar.gz meson-$MV.tar.gz
fetch https://github.com/htacg/tidy-html5/archive/refs/tags/5.8.0.tar.gz tidy-5.8.0.tar.gz
fetch https://downloads.xiph.org/releases/opus/opus-1.3.1.tar.gz opus-1.3.1.tar.gz
fetch https://downloads.xiph.org/releases/ogg/libogg-1.3.5.tar.gz libogg-1.3.5.tar.gz
fetch https://downloads.sourceforge.net/project/pidgin/Pidgin/2.14.13/pidgin-2.14.13.tar.bz2 pidgin-2.14.13.tar.bz2
for t in glib-$GV.tar.xz meson-$MV.tar.gz tidy-5.8.0.tar.gz opus-1.3.1.tar.gz libogg-1.3.5.tar.gz pidgin-2.14.13.tar.bz2; do
    d=${t%.tar.*}; [ "$d" = tidy-5.8.0 ] && d=tidy-html5-5.8.0; untar "$t" "$d"
done
gitat https://github.com/openwebos/db8.git db8 8a9a902
gitat https://github.com/openwebos/luna-service2.git luna-service2 0f384298acde1f3a8bcc509401b1fa7a33ca44f7
gitat https://github.com/openwebos/PmLogLib.git PmLogLib d53ab577991ccb2aa736f935d4b084694fb71e00
rm -rf imlibpurpleservice; gitat "$IMLIB_URL" imlibpurpleservice "$IMLIB_COMMIT"
# PmLogLib.h is generated by its cmake from PmLogLib.h.in; the only substitution is the logging switch.
sed 's/@PMLOG_ENABLE_LOGGING@/1/' PmLogLib/include/public/PmLogLib.h.in > PmLogLib/include/public/PmLogLib.h

# ---- glib: ARM config + generated headers (headers only; no glib is built) --------------------
if [ ! -f "$W/glib-build/gio/gioenumtypes.h" ]; then
    cat > "$W/arm.cross" <<EOF
[binaries]
c = '${TC}gcc'
cpp = '${TC}g++'
ar = '${TC}ar'
strip = '${TC}strip'
pkgconfig = 'false'
[host_machine]
system = 'linux'
cpu_family = 'arm'
cpu = 'armv7'
endian = 'little'
[properties]
needs_exe_wrapper = true
growing_stack = false
have_c99_vsnprintf = true
have_c99_snprintf = true
have_unix98_printf = true
have_strlcpy = false
va_val_copy = true
EOF
    rm -rf "$W/glib-build"
    (cd glib-$GV && python3 ../meson-$MV/meson.py setup "$W/glib-build" --cross-file "$W/arm.cross" \
        -Dlibmount=disabled -Dselinux=disabled -Dxattr=false -Dtests=false -Dnls=disabled \
        -Dman=false -Dgtk_doc=false --wrap-mode=default >/dev/null)
    (cd "$W/glib-build" && ninja gio/gioenumtypes.h gobject/glib-enumtypes.h >/dev/null)
fi
grep -q 'GLIB_SIZEOF_VOID_P 4' "$W/glib-build/glib/glibconfig.h" || { echo "glibconfig.h is not 32-bit" >&2; exit 1; }

# ---- staged headers and link libraries -------------------------------------------------------
P=$W/stage; rm -rf "$P"; mkdir -p "$P/purple/libpurple/media" "$P/opus/opus" "$P/opus/ogg" "$P/lib"
cp pidgin-2.14.13/libpurple/*.h "$P/purple/libpurple/"
cp pidgin-2.14.13/libpurple/media/*.h "$P/purple/libpurple/media/"
cp opus-1.3.1/include/*.h "$P/opus/opus/"
cp libogg-1.3.5/include/ogg/ogg.h libogg-1.3.5/include/ogg/os_types.h "$P/opus/ogg/"
cat > "$P/opus/ogg/config_types.h" <<'EOF'
#ifndef __CONFIG_TYPES_H__
#define __CONFIG_TYPES_H__
/* libogg config_types.h for 32-bit ARM Linux (what configure generates there) */
#include <stdint.h>
typedef int16_t ogg_int16_t;
typedef uint16_t ogg_uint16_t;
typedef int32_t ogg_int32_t;
typedef uint32_t ogg_uint32_t;
typedef int64_t ogg_int64_t;
typedef uint64_t ogg_uint64_t;
#endif
EOF
tar -xzf "$STOCK" -C "$P/lib" --strip-components=3 \
    ./usr/lib/liblunaservice.so ./usr/lib/libmojocore.so ./usr/lib/libmojodb.so ./usr/lib/libmojoluna.so
cp "$O/usr/lib/libpurple.so.0.14.13" "$P/lib/" && ln -sf libpurple.so.0.14.13 "$P/lib/libpurple.so"
for l in glib gio gobject gmodule gthread; do
    cp "$RT/lib$l-2.0.so.0" "$P/lib/" && ln -sf "lib$l-2.0.so.0" "$P/lib/lib$l-2.0.so"
done
cp "$RT/libffi.so.8" "$RT/libz.so.1" "$P/lib/"
for l in tidy.so.58:tidy opus.so.0:opus ogg.so.0:ogg; do
    cp "$RT/lib${l%%:*}" "$P/lib/" && ln -sf "lib${l%%:*}" "$P/lib/lib${l##*:}.so"
done

# ---- compile and link (flags as in Herrie's build.sh) ----------------------------------------
SRC=$W/src/imlibpurpleservice; G=$W/src/glib-$GV; GB=$W/glib-build
OBJ=$W/obj; rm -rf "$OBJ"; mkdir -p "$OBJ"
CXXFLAGS="-std=c++17 -fno-rtti -fpermissive -DMOJ_LINUX -DIMLIBPURPLE_LEGACY_DB8 -O2"
INCLUDES="-I$SRC/inc -I$W/src/db8/inc
  -I$W/src/luna-service2/include/public -I$W/src/luna-service2/include/public/luna-service2
  -I$P/purple/libpurple -I$W/src/PmLogLib/include/public
  -I$W/src/tidy-html5-5.8.0/include -I$P/opus
  -I$G -I$G/glib -I$G/gmodule -I$G/gobject -I$G/gio -I$GB -I$GB/glib -I$GB/gio -I$GB/gobject
  -DGLIB_VERSION_MIN_REQUIRED=GLIB_VERSION_2_70 -DGLIB_VERSION_MAX_ALLOWED=GLIB_VERSION_2_70"
OBJS=""; FAILED=0
for f in "$SRC"/src/*.cpp; do
    b=$(basename "$f" .cpp)
    if "${TC}g++" $CXXFLAGS $INCLUDES -c "$f" -o "$OBJ/$b.o" 2> "$OBJ/$b.log"; then OBJS="$OBJS $OBJ/$b.o"
    else echo "  FAILED: $b.cpp (see $OBJ/$b.log)" >&2; FAILED=1; fi
done
[ "$FAILED" = 0 ] || exit 1
OUT=$W/out/imlibpurpletransport
"${TC}g++" $CXXFLAGS $OBJS -o "$OUT" \
    -Wl,--dynamic-linker=/media/cryptofs/synergy-glibc/lib/ld-linux.so.3 \
    -L"$P/lib" -Wl,-rpath-link,"$P/lib" -Wl,--allow-shlib-undefined \
    -lmojodb -lmojocore -lmojoluna -llunaservice -lpurple -ltidy -lrt -lpthread -lopus -logg \
    -lgio-2.0 -lgobject-2.0 -lglib-2.0

# ---- checks: it must load on the device ------------------------------------------------------
readelf -l "$OUT" | grep -q 'interpreter: /media/cryptofs/synergy-glibc/lib/ld-linux.so.3' \
    || { echo "wrong ELF interpreter" >&2; exit 1; }
want="libmojodb.so libmojocore.so libmojoluna.so liblunaservice.so libpurple.so.0 libtidy.so.58 librt.so.1 libpthread.so.0 libopus.so.0 libogg.so.0 libgio-2.0.so.0 libgobject-2.0.so.0 libglib-2.0.so.0 libstdc++.so.6 libm.so.6 libgcc_s.so.1 libc.so.6"
have=$(readelf -d "$OUT" | sed -n 's/.*Shared library: \[\(.*\)\]/\1/p' | tr '\n' ' ')
for l in $have; do case " $want " in *" $l "*) ;; *) echo "unexpected NEEDED: $l" >&2; exit 1;; esac; done
maxcxx=$(readelf -V "$OUT" | grep -oE 'GLIBCXX_3\.4\.[0-9]+' | sort -t. -k3 -n | tail -1)
maxc=$(readelf -V "$OUT" | grep -oE 'GLIBC_2\.[0-9]+' | sort -t. -k2 -n | tail -1)
[ "${maxcxx##*.}" -le 30 ] || { echo "needs $maxcxx; the device's libstdc++ has 3.4.30" >&2; exit 1; }
[ "${maxc##*.}" -le 23 ] || { echo "needs $maxc; synergy-glibc is 2.23" >&2; exit 1; }
echo "built $OUT ($(stat -c %s "$OUT") bytes, md5 $(md5sum "$OUT" | cut -d' ' -f1)) from imlibpurpleservice $IMLIB_COMMIT"
